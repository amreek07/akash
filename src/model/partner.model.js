const mongoose = require('mongoose');

const partnerSchema = new mongoose.Schema({
    partnerId: {
        type: String,
        required: true,
    },
    name: {
        type: String,
        required: true,
    },
    email: {
        type: String,
        required: true,
    },
    phone: {
        type: String,
        required: true,
    },
    address: {
        type: String,
        required: true,
    },
    city: {
        type: String,
        required: true,
    },
},{ timestamps: true });

const Partner = mongoose.model('Partner', partnerSchema);

module.exports = Partner;